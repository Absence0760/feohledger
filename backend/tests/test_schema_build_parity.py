"""A migrated database and a freshly built one have the SAME schema.

Why this file exists
--------------------
Every database in this project is built one of two ways (`backend/docs/
database.md` § Index parity between the two provisioning paths; this file is
its § Whole-schema parity):

* a database that predates a release gets ``alembic upgrade head`` — every
  revision since ``0001_signup``, applied over whatever ``create_all`` built
  before Alembic existed;
* a NEW tenant gets ``Base.metadata.create_all``
  (``tenant_provisioning._create_tenant_tables``) and a NEW control plane gets
  ``create_all`` + an Alembic stamp at head (``control_plane_bootstrap.
  initialise``, `docs/decisions.md` §274). Neither runs a single revision.

Both are only sound if the chain and the ORM describe the same schema.
``test_migration_model_index_parity.py`` checks that for indexes, statically.
This file checks the WHOLE schema, on a real Postgres: it builds one database
each way and compares columns (type, nullability, server default, identity),
every constraint (primary key, foreign key, unique, check, exclusion) by name
and definition, every index by name and definition, every trigger and the
functions they call, sequences, enum types and extensions.

The migrated side starts from the pre-Alembic schema itself — the
``create_all`` of the models on the day before ``0001_signup``
(``fixtures/pre_0001_schema/``, regenerated by its ``generate.py``) — because
that is the oldest database the chain promises to carry forward.

A difference is a defect in one of the two builds, and gets fixed at its source
(the model, or a new idempotent revision that fans out to every tenant). The
only differences allowed are listed in ``ALLOWED`` below, each with the reason
it is deliberate; an entry that stops matching a real difference fails the
test too, so the list cannot rot.

The databases are throwaway, named per run, and dropped afterwards; nothing
here touches the configured control plane or any real tenant.
"""

