@pytest.fixture
async def scratch():
    """A factory of throwaway databases on the local Postgres, all dropped on
    teardown. Skips when Postgres is unreachable, like the realdb harness."""
    dsn = _parse_maintenance_dsn()
    try:
        maint = await asyncpg.connect(**dsn)
    except (OSError, asyncpg.PostgresError) as exc:
        pytest.skip(f"requires a live Postgres (pnpm db:up): {exc}")
    run = uuid.uuid4().hex[:10]
    made: list[str] = []

    async def make(role: str) -> tuple[str, dict]:
        name = f"feoh_schemaeq_{run}_{role}"
        await maint.execute(f'CREATE DATABASE "{name}"')
        made.append(name)
        return name, {**dsn, "database": name}

    try:
        yield make
    finally:
        for name in made:
            await maint.execute(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)')
        await maint.close()


def _alembic_upgrade(env_overrides: dict[str, str]) -> None:
    env = {**os.environ, **env_overrides}
    if "FEOH_MIGRATE_TENANT" not in env_overrides:
        env.pop("FEOH_MIGRATE_TENANT", None)
    result = subprocess.run(
        [sys.executable, "-m", "alembic", "upgrade", "head"],
        cwd=BACKEND,
        env=env,
        capture_output=True,
        text=True,
        timeout=480,
    )
    assert result.returncode == 0, (
        "the Alembic chain failed on a pre-0001 database:\n" + result.stderr[-4000:]
    )


async def _load_pre_0001(dsn: dict, which: str) -> None:
    conn = await asyncpg.connect(**dsn)
    try:
        await conn.execute((FIXTURES / f"{which}.sql").read_text())
    finally:
        await conn.close()


def _head() -> str:
    from scripts.init_control_plane import head_revision

    return head_revision()


def _revision_below_0113() -> str:
    from alembic.config import Config
    from alembic.script import ScriptDirectory

    script = ScriptDirectory.from_config(Config(str(BACKEND / "alembic.ini")))
    return script.get_revision("0113_schema_build_parity").down_revision


def _check(side: str, found: dict[tuple[str, str], str]) -> None:
    unexpected = {k: v for k, v in found.items() if k not in ALLOWED[side]}
    assert not unexpected, (
        f"the migrated and freshly built {side} schemas differ — fix the model or add "
        f"an idempotent revision (or, if it is deliberate, an ALLOWED entry):\n"
        + _report(unexpected)
    )
    stale = set(ALLOWED[side]) - set(found)
    assert not stale, f"ALLOWED[{side!r}] entries no longer differ — remove them: {sorted(stale)}"


async def test_a_migrated_tenant_matches_a_freshly_provisioned_one(scratch):
    migrated_name, migrated_dsn = await scratch("tm")
    await _load_pre_0001(migrated_dsn, "tenant")
    _alembic_upgrade({"FEOH_MIGRATE_TENANT": migrated_name})

    fresh_name, fresh_dsn = await scratch("tf")
    await _create_tenant_tables(fresh_name)

    migrated = await snapshot(migrated_dsn)
    fresh = await snapshot(fresh_dsn)
    # The version table is Alembic's bookkeeping, present only where it ran;
    # a fresh tenant is never stamped (migrate_all_tenants replays the chain's
    # no-op guards onto it the first time it runs).
    _drop_version_table(migrated, fresh)
    _check("tenant", diff(migrated, fresh))


def _drop_version_table(*snaps: dict) -> None:
    for snap in snaps:
        for key in [k for k in snap if k[1].split(".")[0] == "alembic_version"]:
            del snap[key]


async def test_the_first_deploy_after_provisioning_leaves_a_fresh_tenant_alone(scratch):
    """A new tenant is built by ``create_all`` and NOT stamped, so the next
    ``deploy.sh`` (``migrate_all_tenants.py``) replays the WHOLE chain over it.
    That is every production tenant's real history, so the replay must change
    nothing: each revision's guards have to recognise the ORM's spelling of
    what it would build, not only its own."""
    name, dsn = await scratch("tr")
    await _create_tenant_tables(name)
    before = await snapshot(dsn)
    _alembic_upgrade({"FEOH_MIGRATE_TENANT": name})
    after = await snapshot(dsn)
    _drop_version_table(after)
    _check("tenant", diff(after, before))


async def test_0113_removes_the_duplicate_fks_an_earlier_replay_left(scratch):
    """Production tenants provisioned before 0029 / 0051 / 0082 learned the
    ORM's FK names already carry the duplicates their first deploy added. 0113
    must drop them — keeping the ORM's — on a tenant stamped just below it."""
    name, dsn = await scratch("td")
    await _create_tenant_tables(name)
    before = await snapshot(dsn)
    conn = await asyncpg.connect(**dsn)
    try:
        for table, column, ref, fk in [
            ("invoices", "entity_id", "entities", "fk_invoices_entity"),
            ("vendors", "entity_id", "entities", "fk_vendors_entity"),
            ("payments", "retry_of_payment_id", "payments", "fk_payments_retry_of_payment_id"),
        ]:
            await conn.execute(
                f'ALTER TABLE "{table}" ADD CONSTRAINT "{fk}" '
                f'FOREIGN KEY ("{column}") REFERENCES "{ref}" (id)'
            )
        await conn.execute("CREATE TABLE alembic_version (version_num varchar(32) PRIMARY KEY)")
        await conn.execute("INSERT INTO alembic_version VALUES ($1)", _revision_below_0113())
    finally:
        await conn.close()
    _alembic_upgrade({"FEOH_MIGRATE_TENANT": name})
    after = await snapshot(dsn)
    _drop_version_table(after)
    _check("tenant", diff(after, before))


def _control_scope() -> frozenset[str]:
    # Before Alembic, `seed.py` built the control plane with `create_all` of
    # EVERY model, so a pre-0001 control plane also holds empty copies of the
    # tenant tables, and the chain carries them forward. They are inert — no
    # code reads tenant tables from the control plane — and a fresh control
    # plane deliberately never creates them (`control_plane_bootstrap.
    # _control_tables`), so only the control tables are compared.
    return CONTROL_TABLES | {"alembic_version"}


#: The four tables a control plane held before Alembic, by the classification
#: of the day (`scripts/create_tenant.py` at f6d93ab1^).
_PRE_0001_CONTROL_TABLES = ("organizations", "users", "roles", "user_roles")


@pytest.mark.parametrize("baseline", ["as_seeded", "control_tables_only"])
async def test_a_migrated_control_plane_matches_a_freshly_initialised_one(scratch, baseline):
    """``as_seeded`` is the control plane `seed.py` really built, tenant-table
    copies and all. Many revisions pick their branch by probing for
    ``invoices``, so on it they take the TENANT branch and their control-plane
    DDL never runs; ``control_tables_only`` drops the copies first, which is the
    database those control branches were written for, so their DDL is compared
    too (0032 built ``assistant_usage`` with defaults the model lacks, and only
    this baseline shows it)."""
    migrated_name, migrated_dsn = await scratch("cm")
    await _load_pre_0001(migrated_dsn, "control")
    if baseline == "control_tables_only":
        conn = await asyncpg.connect(**migrated_dsn)
        try:
            copies = [
                r["tablename"]
                for r in await conn.fetch(
                    "SELECT tablename FROM pg_tables WHERE schemaname = 'public'"
                )
                if r["tablename"] not in _PRE_0001_CONTROL_TABLES
            ]
            await conn.execute("DROP TABLE " + ", ".join(f'"{t}"' for t in copies) + " CASCADE")
        finally:
            await conn.close()
    _alembic_upgrade({"FEOH_DATABASE_URL": _make_tenant_url(migrated_name)})

    fresh_name, fresh_dsn = await scratch("cf")
    engine = create_async_engine(_make_tenant_url(fresh_name))
    try:
        await initialise(engine, _head())
    finally:
        await engine.dispose()

    scope = _control_scope()
    migrated = await snapshot(migrated_dsn, scope)
    fresh = await snapshot(fresh_dsn, scope)
    _check(f"control/{baseline}", diff(migrated, fresh))
