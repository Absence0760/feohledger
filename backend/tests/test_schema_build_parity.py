async def test_a_migrated_control_plane_matches_a_freshly_initialised_one(scratch, baseline):
    """``as_seeded`` is the control plane `seed.py` really built, tenant-table
    copies and all. Many revisions pick their branch by probing for
    ``invoices``, so on it they take the TENANT branch and their control-plane
    DDL never runs; ``control_tables_only`` drops the copies first, which is the
    database those control branches were written for, so their DDL is compared
    too (0032 built ``assistant_usage`` with defaults the model lacks, and only
    this baseline shows it)."""
    migrated_name, migrated_dsn = await scratch("cm")
    await _load_pre_0001(migrated_dsn, "control")
    if baseline == "control_tables_only":
        conn = await asyncpg.connect(**migrated_dsn)
        try:
            copies = [
                r["tablename"]
                for r in await conn.fetch(
                    "SELECT tablename FROM pg_tables WHERE schemaname = 'public'"
                )
                if r["tablename"] not in _PRE_0001_CONTROL_TABLES
            ]
            await conn.execute("DROP TABLE " + ", ".join(f'"{t}"' for t in copies) + " CASCADE")
        finally:
            await conn.close()
    _alembic_upgrade({"FEOH_DATABASE_URL": _make_tenant_url(migrated_name)})

    fresh_name, fresh_dsn = await scratch("cf")
    engine = create_async_engine(_make_tenant_url(fresh_name))
    try:
        await initialise(engine, _head())
    finally:
        await engine.dispose()

    scope = _control_scope()
    migrated = await snapshot(migrated_dsn, scope)
    fresh = await snapshot(fresh_dsn, scope)
    _check(f"control/{baseline}", diff(migrated, fresh))
