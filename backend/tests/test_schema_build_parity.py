# ── Catalogue snapshot ───────────────────────────────────────────────────────

_COLUMNS = """
SELECT c.relname AS tbl, a.attname AS col,
       format_type(a.atttypid, a.atttypmod) AS type,
       a.attnotnull AS not_null,
       pg_get_expr(d.adbin, d.adrelid) AS default,
       a.attidentity AS identity, a.attgenerated AS generated,
       (SELECT collname FROM pg_collation WHERE oid = a.attcollation) AS collation
FROM pg_attribute a
JOIN pg_class c ON c.oid = a.attrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p')
  AND a.attnum > 0 AND NOT a.attisdropped
"""

_CONSTRAINTS = """
SELECT c.relname AS tbl, k.conname AS name, k.contype AS kind,
       pg_get_constraintdef(k.oid) AS def
FROM pg_constraint k
JOIN pg_class c ON c.oid = k.conrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public'
"""

_INDEXES = """
SELECT c.relname AS tbl, i.relname AS name, pg_get_indexdef(x.indexrelid) AS def,
       x.indisvalid AS valid, x.indisready AS ready
FROM pg_index x
JOIN pg_class i ON i.oid = x.indexrelid
JOIN pg_class c ON c.oid = x.indrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public'
"""

_TRIGGERS = """
SELECT c.relname AS tbl, t.tgname AS name, pg_get_triggerdef(t.oid) AS def,
       t.tgenabled AS enabled
FROM pg_trigger t
JOIN pg_class c ON c.oid = t.tgrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND NOT t.tgisinternal
"""

_FUNCTIONS = """
SELECT p.proname AS name, pg_get_function_identity_arguments(p.oid) AS args,
       p.prosrc AS src, l.lanname AS lang, p.prosecdef AS security_definer,
       p.provolatile AS volatility, p.prorettype::regtype::text AS returns
FROM pg_proc p
JOIN pg_namespace n ON n.oid = p.pronamespace
JOIN pg_language l ON l.oid = p.prolang
WHERE n.nspname = 'public'
  AND NOT EXISTS (
      SELECT 1 FROM pg_depend d
      WHERE d.objid = p.oid AND d.deptype = 'e'
  )
"""

_SEQUENCES = """
SELECT sequencename AS name, data_type::text AS type, increment_by, min_value,
       max_value, start_value, cycle
FROM pg_sequences WHERE schemaname = 'public'
"""

_ENUMS = """
SELECT t.typname AS name, array_agg(e.enumlabel ORDER BY e.enumsortorder) AS labels
FROM pg_type t
JOIN pg_enum e ON e.enumtypid = t.oid
JOIN pg_namespace n ON n.oid = t.typnamespace
WHERE n.nspname = 'public'
GROUP BY t.typname
"""

_EXTENSIONS = "SELECT extname AS name FROM pg_extension WHERE extname <> 'plpgsql'"


def _norm(text: str | None) -> str | None:
    """Whitespace-insensitive, so a function body indented differently in a
    revision than in its Python helper is not a schema difference."""
    return None if text is None else " ".join(text.split())


async def snapshot(dsn: dict, tables: frozenset[str] | None = None) -> dict:
    """Every schema object, keyed ``(kind, identity) -> definition``.

    ``tables`` restricts table-owned objects to that set (the control plane's
    migrated side carries the pre-Alembic tenant tables too — see
    ``_control_scope``).
    """
    conn = await asyncpg.connect(**dsn)
    try:
        objects: dict[tuple[str, str], object] = {}

        def keep(tbl: str) -> bool:
            return tables is None or tbl in tables

        for r in await conn.fetch(
            "SELECT relname, relrowsecurity, relforcerowsecurity, reloptions "
            "FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
            "WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p')"
        ):
            if keep(r["relname"]):
                objects[("table", r["relname"])] = (
                    r["relrowsecurity"],
                    r["relforcerowsecurity"],
                    tuple(r["reloptions"] or ()),
                )
        for r in await conn.fetch(_COLUMNS):
            if keep(r["tbl"]):
                objects[("column", f"{r['tbl']}.{r['col']}")] = (
                    r["type"],
                    "NOT NULL" if r["not_null"] else "NULL",
                    r["default"],
                    r["identity"] or None,
                    r["generated"] or None,
                    r["collation"],
                )
        for r in await conn.fetch(_CONSTRAINTS):
            if keep(r["tbl"]):
                objects[("constraint", f"{r['tbl']}.{r['name']}")] = (r["kind"], r["def"])
        for r in await conn.fetch(_INDEXES):
            if keep(r["tbl"]):
                objects[("index", f"{r['tbl']}.{r['name']}")] = (
                    r["def"],
                    r["valid"],
                    r["ready"],
                )
        for r in await conn.fetch(_TRIGGERS):
            if keep(r["tbl"]):
                objects[("trigger", f"{r['tbl']}.{r['name']}")] = (r["def"], r["enabled"])
        for r in await conn.fetch(_FUNCTIONS):
            objects[("function", f"{r['name']}({r['args']})")] = (
                _norm(r["src"]),
                r["lang"],
                r["security_definer"],
                r["volatility"],
                r["returns"],
            )
        for r in await conn.fetch(_SEQUENCES):
            objects[("sequence", r["name"])] = tuple(r.values())[1:]
        for r in await conn.fetch(_ENUMS):
            objects[("enum", r["name"])] = tuple(r["labels"])
        for r in await conn.fetch(_EXTENSIONS):
            objects[("extension", r["name"])] = True
        return objects
    finally:
        await conn.close()


def diff(migrated: dict, fresh: dict) -> dict[tuple[str, str], str]:
    out: dict[tuple[str, str], str] = {}
    for key in sorted(migrated.keys() | fresh.keys()):
        if key not in fresh:
            out[key] = f"only on the MIGRATED side: {migrated[key]!r}"
        elif key not in migrated:
            out[key] = f"only on the FRESH side: {fresh[key]!r}"
        elif migrated[key] != fresh[key]:
            out[key] = f"migrated {migrated[key]!r} != fresh {fresh[key]!r}"
    return out


def _report(found: dict[tuple[str, str], str]) -> str:
    return "\n".join(f"  {kind:<10} {key}: {what}" for (kind, key), what in found.items())


